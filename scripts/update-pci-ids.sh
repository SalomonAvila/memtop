#!/usr/bin/env sh
# Regenerates data/pci-gpu.ids: an extract of the official pci.ids database
# (https://pci-ids.ucw.cz) with only the GPU vendors that memtop recognizes.
#
# Usage:
#   scripts/update-pci-ids.sh                 # downloads the latest version
#   scripts/update-pci-ids.sh /path/pci.ids   # uses a local file
#
# pci.ids is distributed under GPL-2.0-or-later or BSD-3-Clause; its original
# header with the license notice is kept.
set -eu

output="$(dirname "$0")/../data/pci-gpu.ids"
input="${1:-}"

if [ -z "$input" ]; then
    input="$(mktemp)"
    trap 'rm -f "$input"' EXIT
    curl -fsSL https://pci-ids.ucw.cz/v2.2/pci.ids -o "$input"
fi

# Vendors: NVIDIA, AMD/ATI, Intel, Matrox, Cirrus, ASPEED, Qualcomm, Microsoft (Hyper-V),
# VMware, VirtualBox, Red Hat/QEMU (virtio, bochs), Moore Threads.
awk '
    BEGIN {
        split("10de 1002 1022 8086 102b 1013 1a03 5143 1414 15ad 80ee 1af4 1b36 1234 1ed5", v, " ")
        for (i in v) wanted[v[i]] = 1
        print "#\tExtract of pci.ids for memtop: GPU vendors only, no subsystems."
        print "#\tGenerated by scripts/update-pci-ids.sh. Do not edit by hand."
    }
    /^C / { exit }                       # the class list starts: no more vendors
    NR <= 20 && /^#/ { print; next }     # original header (version and license)
    /^#/ || /^[[:space:]]*$/ { next }
    /^\t\t/ { next }                     # subsystems
    /^\t/ { if (inside) print; next }    # devices
    { inside = (substr($0, 1, 4) in wanted); if (inside) print }
' "$input" > "$output"

echo "Wrote $output ($(wc -l < "$output") lines)"
